class Doctor {
  final int id;
  final String name;
  final String specialization;
  final String experience;
  final int rating;
  final String imageUrl;
  final int price;

  Doctor({
    required this.id,
    required this.name,
    required this.specialization,
    required this.experience,
    required this.rating,
    required this.imageUrl,
    required this.price,
  });
}
